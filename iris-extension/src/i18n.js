function irisT(language, key, vars) {
  const table = (language && IRIS_I18N[language]) || IRIS_I18N.en;
  const template = table[key] || IRIS_I18N.en[key] || key;
  if (!vars || !vars.length) return template;
  return template.replace(/\{(\d+)\}/g, (match, index) =>
    vars[index] === undefined ? match : String(vars[index])
  );
}
